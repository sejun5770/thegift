-- ============================================
-- 068_bg_product_settings_cost.sql
--
-- 상품 원가 — 로켓그로스 실질 마진 계산용.
--
-- 배경 (운영 요청 2026-08-18):
--   로켓그로스 화면은 매출·수수료·물류비까지 반영해 정산금액을 보여주지만, 그건
--   '쿠팡이 정산해 주는 돈' 이지 우리에게 남는 돈이 아니다. 상품 매입 원가와
--   창고 입고에 드는 비용을 빼야 실제 마진이 나온다.
--
-- 두 컬럼으로 나눈 이유:
--   · unit_cost         상품 자체 매입가. 거래처와의 단가라 비교적 안정적이다.
--   · inbound_unit_cost 창고 입고 부대비용(입고 배송비 등)을 개당으로 환산한 값.
--     실제로는 입고 회차·박스 단위로 발생하므로 개당 정액이 근사치다. 그래서
--     원가와 합쳐 한 칸으로 두지 않는다 — 합치면 나중에 회차 기반으로 정교화할 때
--     과거 값이 무엇이었는지 되짚을 수 없다.
--
-- 기준:
--   둘 다 '상품 1개당 · 부가세 별도' 금액으로 입력한다 (화면 라벨에도 명시).
--   NULL = 미입력. 0 과 구분해야 한다 — 0 은 '원가 없음(사은품 등)' 이고
--   NULL 은 '아직 모름' 이라 마진을 계산하면 안 되는 상태다.
-- ============================================

ALTER TABLE bg_product_settings
  ADD COLUMN IF NOT EXISTS unit_cost         NUMERIC(12, 2),
  ADD COLUMN IF NOT EXISTS inbound_unit_cost NUMERIC(12, 2);

COMMENT ON COLUMN bg_product_settings.unit_cost IS
  '상품 1개당 매입 원가 (부가세 별도). NULL = 미입력이라 마진 계산 제외';
COMMENT ON COLUMN bg_product_settings.inbound_unit_cost IS
  '상품 1개당 창고 입고 부대비용 (입고 배송비 등, 부가세 별도). 회차 단위 실비를 개당으로 환산한 근사치';
