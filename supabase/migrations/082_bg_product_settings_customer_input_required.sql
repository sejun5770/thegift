-- ============================================
-- 082_bg_product_settings_customer_input_required.sql
--
-- 고객 정보입력이 필요 없는 상품 (샘플세트 TGSAMPLE01~07 등) — 상품 단위 예외.
--
-- 배경 (2026-09-14 운영 요청):
--   샘플세트는 희망출고일·커스텀 스티커 없이 일반 부가상품처럼 주문된다. 지금은 채널 단위 예외
--   (쿠팡·네이버·수동)만 있어, 바른손몰·바른손카드에서 이런 상품만 주문하면 미입력 탭에 쌓이고
--   고객정보 행이 없어 수집완료도 안 된다.
--
-- 동작:
--   · 이 상품만 있는 주문 → 정보입력현황이 로드 때 고객정보 스텁을 자동 생성 (스티커 없음,
--     희망출고일 = 주문일 다음 영업일) → 바로 입력완료. 행에 '입력 불필요' 배지.
--   · 다른 답례품과 섞인 주문 → 고객 화면에서 이 상품만 입력 대상에서 빠진다.
--   · 고객이 링크를 열면 입력 화면 대신 '입력할 정보가 없어요' 안내.
--
-- 기존 rows 는 true (forward-only). 컬럼이 없으면 상품설정 신규 저장이 실패하므로 배포 전에 적용한다.
-- ============================================

ALTER TABLE bg_product_settings
  ADD COLUMN IF NOT EXISTS customer_input_required BOOLEAN NOT NULL DEFAULT true;

COMMENT ON COLUMN bg_product_settings.customer_input_required IS 'false = 고객 정보입력 불필요 상품 (샘플세트 등). 이 상품만 있는 주문은 자동 입력완료, 섞인 주문에선 입력 대상에서 제외.';
