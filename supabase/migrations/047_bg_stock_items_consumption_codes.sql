-- ============================================
-- 047_bg_stock_items_consumption_codes.sql
--
-- 재고 소진 수량을 매출과 분리해 집계하기 위한 소진코드 추가 (운영 결정 2026-08-05).
--
-- 배경:
--   한 원물이 단독으로도 팔리고 여러 세트에도 들어간다. 재고는 그 모든 경로에서
--   차감되는데 매출코드만으로 수량을 세면 소진예상일이 실제보다 길게 나온다.
--     주방세제(TGJBK03O1) 현재고 8,156
--       단독 코드만        144개/30일 → 1,699일
--       실제 소비 경로 전부 329개/30일 →   743일  (2.3배 차이)
--
--   배수도 필요하다. 세트 1개에 원물이 여러 개 들어가는 경우가 있다.
--     데일리너츠: 세트 1개당 원물 5개 차감
--
-- 형식:
--   consumption_codes = 'CODE, CODE2*5, CODE3*2'
--     · 콤마 구분, 각 코드 뒤에 *배수 (생략 시 1)
--     · 비우면 sales_codes 를 배수 1 로 사용 → 기존 등록은 동작 변화 없음
--
--   소진 수량 = Σ( 각 코드의 30일 판매수량 × 배수 )
--   일평균 / 소진예상일은 이 값으로 계산하고,
--   매출액·실판매가는 계속 sales_codes 로 계산한다.
-- ============================================

ALTER TABLE bg_stock_items ADD COLUMN IF NOT EXISTS consumption_codes TEXT;

COMMENT ON COLUMN bg_stock_items.consumption_codes IS
  '재고 소진 수량 집계용 코드. 콤마 구분, 코드*배수 형식(예: TGJSD03D1*5). 비우면 sales_codes 를 배수 1 로 사용';
