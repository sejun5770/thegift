-- ============================================
-- 072_rg_unit_plan_list_price.sql
--
-- 판매단위 기획에 정가(할인 전 표시가)를 추가한다.
--
-- 배경 (운영 요청 2026-08-19):
--   판매가는 쿠팡지원할인 등을 뺀 실제 매출인식액 기준인데, 기획 단계에서는
--   "정가 얼마로 걸고 얼마까지 할인할 것인가" 를 함께 본다.
--   정가만으로는 마진이 나오지 않으므로 계산에는 쓰지 않고, 판매가와 나란히 두어
--   할인율이 얼마인지 드러내는 용도다.
--
-- 단위는 판매가와 같다:
--   list_price_per_item  원 / 상품 1개(낱개), 부가세 포함
--   화면의 '정가' = list_price_per_item × sales_unit  (판매가와 같은 방식으로 곱한다)
--
--   개당 값을 저장하는 이유: 판매단위를 바꾸면 정가도 따라가야 하는데,
--   총액을 저장하면 판매단위 변경 시 어느 쪽을 고정할지 알 수 없다.
--   판매가(price)는 총액을 저장하지만 그건 실제 매출인식액이라 그 자체가 사실이고,
--   정가는 "낱개 얼마짜리를 몇 개 묶어 판다" 는 기획 값이라 개당이 정본이다.
-- ============================================

ALTER TABLE coupang_rg_unit_plan
  ADD COLUMN IF NOT EXISTS list_price_per_item NUMERIC(12, 2);

COMMENT ON COLUMN coupang_rg_unit_plan.list_price_per_item IS
  '정가 (원/상품 1개, 부가세 포함). 화면의 정가 = 이 값 × sales_unit. 마진 계산에는 쓰지 않고 할인율 표시용';
